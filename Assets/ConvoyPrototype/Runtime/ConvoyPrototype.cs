        private void Start()
        {
            if (van == null || road == null || player == null || gunCamera == null || vanHitbox == null ||
                ammoSupply == null || ammoReceiver == null || mainVanModel == null ||
                mainVanModelPrefab == null || pursuerVanModelPrefab == null ||
                playerAvatarPrefab == null || player2AvatarPrefab == null)
            {
                Debug.LogError("Convoy scene is incomplete. Use Tools > Convoy > Create Prototype Scene.", this);
                enabled = false;
                return;
            }

            audioSource = gameObject.AddComponent<AudioSource>();
            audioSource.spatialBlend = 0f;
            shotSound = MakeSound("Rail discharge", 0.28f, 130f, 0.35f);
            crashSound = MakeSound("Body impact", 0.3f, 65f, 0.65f);
            explosionSound = MakeSound("Explosion", 0.6f, 45f, 0.8f);
            PrototypeGeometry.BuildDriverStation(this);
            PrototypeGeometry.BuildAccelerator(this);
            PrototypeGeometry.BuildRoadRocks(this);
            PrototypeGeometry.ExtendRoad(this);
            player.view.farClipPlane = ViewDistance;
            SetPaused(ChoosingRole);
            if (!Application.isFocused)
                OnApplicationFocus(false);
            spawnTimer = spawnInterval;
            if (!ChoosingRole)
                SpawnPursuer(-1, -65f);
        }

        public void SelectRole(PlayerRole role)
        {
            if (!ChoosingRole || (role != PlayerRole.Gunner && role != PlayerRole.Driver))
                throw new System.InvalidOperationException("Choose Player 1 or Player 2 from the startup selector.");
            Role = role;
            Tutorial.Reset();
            PrototypeGeometry.BuildAvatar(player);
            if (DriverPractice)
            {
                foreach (PursuerVan enemy in Pursuers)
                {
                    enemy.gameObject.SetActive(false);
                    Destroy(enemy.gameObject);
                }
                Pursuers.Clear();
                player.SetSpawn(DriverSpawn, Quaternion.identity);
                roadRocks.BeginPractice();
            }
            else
                SpawnPursuer(-1, -65f);
            spawnTimer = spawnInterval;
            SetPaused(false);
        }

        public void Steer(float input, float dt, ConvoyPlayer actor = null)
        {
            actor = actor != null ? actor : player;
            if (Online && !network.World.ExecutingCommand)
            {
                network.SteeringInput = input;
                return;
            }
            if (actor.Role != PlayerRole.Driver || !SimulationRunning || !actor.Driving)
                return;
            float previousOffset = SteeringOffset;
            SteeringOffset = Mathf.Clamp(SteeringOffset + Mathf.Clamp(input, -1f, 1f) * SteeringSpeed *
                (CurrentSpeed / roadSpeed) * dt,
                -RoadEdge, RoadEdge);
            if (actor.IsLocal)
                Tutorial.ObserveSteering(Mathf.Abs(SteeringOffset - previousOffset));
            Transform wheel = van.Find("Driver steering wheel");
            if (wheel != null)
                wheel.localRotation = Quaternion.Euler(20f, 0f, -Mathf.Clamp(input, -1f, 1f) * 25f);
        }

        private void Update()
        {
            Keyboard keyboard = Keyboard.current;
            Mouse mouse = Mouse.current;
            if (ChoosingRole)
                return;
            if (pausedForFocus && Application.isFocused)
                OnApplicationFocus(true);
            if (!Online && IsDead && keyboard != null && keyboard.rKey.wasPressedThisFrame)
            {
                SceneManager.LoadSceneAsync(gameObject.scene.path);
                return;
            }
            if (keyboard != null && keyboard.escapeKey.wasPressedThisFrame)
                SetPaused(!Paused);
            else if (!Online && Paused && Application.isFocused && mouse != null && mouse.leftButton.wasPressedThisFrame)
                SetPaused(false);

            if (Paused && !Online)
                return;

            float dt = Time.deltaTime;
            if (!WorldAuthority)
            {
                UpdateEffects(dt);
                return;
            }
            healthDisplayAge += dt;
            DamageFlash = Mathf.MoveTowards(DamageFlash, 0f, dt * 1.8f);
            UpdateRig(dt);
            UpdateEffects(dt);
            if (!SimulationRunning)
                return;
            AdvanceDifficulty(dt);
            accelerator.Step(dt);
            DistanceTravelled += CurrentSpeed * dt;
            ScrollRoad(dt);
            roadRocks.Step(dt);
            Cooldown = Mathf.Max(0f, Cooldown - dt);
            HitMarker = Mathf.Max(0f, HitMarker - dt);
            shotKick = Mathf.MoveTowards(shotKick, 0f, dt * 12f);

            spawnTimer -= dt;
            if (!DriverPractice && spawnTimer <= 0f && Pursuers.Count < CurrentPursuerLimit)
            {
                SpawnPursuer(spawnIndex++ % 2 == 0 ? -1 : 1, -100f);
                spawnTimer = CurrentSpawnInterval;
            }
        }

        public void AdvanceDifficulty(float dt)
        {
            if (float.IsNaN(dt) || float.IsInfinity(dt) || dt < 0f)
                throw new System.ArgumentOutOfRangeException(nameof(dt));
            if (!WorldAuthority || !SimulationRunning)
                return;
            int previousStage = DifficultyStage;
            SurvivalTime += dt;
            if (DifficultyStage != previousStage)
                spawnTimer = Mathf.Min(spawnTimer, CurrentSpawnInterval);
        }

        private void LateUpdate()
        {
            Tutorial.Tick(Time.unscaledDeltaTime);
            if (gunAmmoDisplay != null)
            {
                gunAmmoDisplay.transform.parent.gameObject.SetActive(Mounted && !IsDead);
                gunAmmoDisplay.text = ShotsAvailable.ToString();
                UpdateChargeDisplay();
            }
            if (gun == null)
                return;
            Mouse mouse = Mouse.current;
            if (SimulationRunning && !Paused && Mounted && mouse != null)
            {
                Vector2 look = mouse.delta.ReadValue() * 0.16f;
                gunYaw = Mathf.Clamp(gunYaw + look.x, -75f, 75f);
                gunPitch = Mathf.Clamp(gunPitch - look.y, -24f, 20f);
            }
            gun.localRotation = Quaternion.Euler(gunPitch, 180f + gunYaw, 0f);
            gunCamera.transform.localPosition = new Vector3(0f, 0.2f, -0.65f - shotKick * 0.045f);
            gunCamera.transform.localRotation = Quaternion.Euler(-shotKick, 0f, roll * -0.25f);
            if (SimulationRunning && !Paused && Mounted && mouse != null && mouse.leftButton.wasPressedThisFrame)
                TryFire();
        }

        public void SetPaused(bool paused)
        {
            pausedForFocus = false;
            Paused = paused;
            if (paused && player != null)
            {
                player.Dismount();
                if (!Online)
                {
                    player.ReleaseAmmo(false);
                    if (accelerator != null)
                        accelerator.ReleaseRock();
                }
            }
            Cursor.lockState = paused || IsDead || ChoosingRole ? CursorLockMode.None : CursorLockMode.Locked;
            Cursor.visible = paused || IsDead || ChoosingRole;
        }

        private void OnApplicationFocus(bool focused)
        {
            if (!focused && !Paused)
            {
                SetPaused(true);
                pausedForFocus = true;
            }
            else if (focused && pausedForFocus)
                SetPaused(false);
        }

        private void OnDisable()
        {
            Cursor.lockState = CursorLockMode.None;
            Cursor.visible = true;
        }

        private void OnDestroy()
        {
            pixelUI?.Dispose();
            if (chargeSprite != null) Destroy(chargeSprite);
            if (chargeTexture != null) Destroy(chargeTexture);
            if (shotSound != null) Destroy(shotSound);
            if (crashSound != null) Destroy(crashSound);
            if (explosionSound != null) Destroy(explosionSound);
        }

        public void ScrollRoad(float dt)
        {
            foreach (Transform segment in road)
            {
                Vector3 p = segment.localPosition;
                p.z = WrapRoadPosition(p.z - CurrentSpeed * dt);
                segment.localPosition = p;
            }
        }

        public static float WrapRoadPosition(float z)
        {
            return RoadRear + Mathf.Repeat(z - RoadRear, SegmentCount * SegmentLength);
        }

        private void UpdateRig(float dt)
        {
            // Substeps keep the damped suspension stable during editor hitches.
            float remaining = Mathf.Min(dt, 0.15f);
            while (remaining > 0f)
            {
                float step = Mathf.Min(remaining, 0.01f);
                rigVelocity += (-rigOffset * 48f - rigVelocity * 10f) * step;
                rigOffset += rigVelocity * step;
                rollVelocity += (-roll * 54f - rollVelocity * 9f) * step;
                roll += rollVelocity * step;
                remaining -= step;
            }
            float t = DistanceTravelled / roadSpeed;
            van.localPosition = new Vector3(SteeringOffset + rigOffset.x, 1.05f + Mathf.Sin(t * 9f) * 0.018f, 0f);
            van.localRotation = Quaternion.Euler(Mathf.Sin(t * 4.3f) * 0.22f, 0f, roll + Mathf.Sin(t * 3f) * 0.3f);
        }

        public void RegisterRam(int side)
        {
            if (!WorldAuthority || IsDead || (!Online && player.IsRespawning))
                return;
            side = side < 0 ? -1 : 1;
            RamCount++;
            accelerator.RegisterImpact();
            DamageFlash = 1f;
            healthDisplayAge = 0f;
            rigVelocity.x -= side * 2.8f;
            rollVelocity += side * 50f;
            player.AddImpact(Vector3.left * (side * 3.8f), -side * 9f);
            if (otherPlayer != null)
                otherPlayer.AddImpact(Vector3.left * (side * 3.8f), -side * 9f);
            if (Online)
                network.World.BroadcastImpact(side);
            PlaySound(crashSound, 0.65f);
            if (IsDead)
            {
                player.Dismount();
                player.ReleaseAmmo(false);
                if (otherPlayer != null)
                {
                    otherPlayer.Dismount();
                    otherPlayer.ReleaseAmmo(false);
                }
                SetPaused(false);
                accelerator.ReleaseRock();
                PlaySound(explosionSound, 0.5f);
            }
        }

        public bool TryRegisterRam(PursuerVan enemy, Vector3 contactPosition)
        {
            if (!WorldAuthority || IsDead || (!Online && player.IsRespawning) || enemy.IsDestroyed)
                return false;
            Physics.SyncTransforms();
            Vector3 offset = enemy.transform.parent.TransformPoint(contactPosition) - enemy.transform.position;
            foreach (Collider shape in enemy.GetComponentsInChildren<Collider>())
            {
                if (!shape.enabled || shape.isTrigger)
                    continue;
                Bounds bounds = shape.bounds;
                bounds.center += offset;
                // Match the ram's contact tolerance at touching faces.
                bounds.Expand(0.02f);
                if (!vanHitbox.bounds.Intersects(bounds))
                    continue;
                RegisterRam(enemy.Side);
                return true;
            }
            return false;
        }

        public PursuerVan SpawnPursuer(int side, float z)
        {
            if (DriverPractice)
                throw new System.InvalidOperationException("Pursuers are disabled in driver practice.");
            PursuerVan enemy = PrototypeGeometry.CreatePursuer(this, side, z);
            Pursuers.Add(enemy);
            return enemy;
        }

        public bool TryFire(ConvoyPlayer actor = null)
        {
            actor = actor != null ? actor : player;
            if (Online && !network.World.ExecutingCommand)
            {
                network.World.SendAction(ConvoyNetworkWorld.Action.Fire);
                return false;
            }
            if (!actor.Mounted || actor.Role == PlayerRole.Driver || Cooldown > 0f || !SimulationRunning || ShotsAvailable <= 0)
                return false;

            ShotsAvailable--;
            RecordLesson(actor, ConvoyTutorial.Lesson.GunFire);
            Cooldown = 0.8f;
            shotKick = 3f;
            Ray ray = gunCamera.ViewportPointToRay(new Vector3(0.5f, 0.5f));
            Vector3 end = ray.GetPoint(180f);
            // The cabin and gun are layer 8; a shot must leave the player's van.
            Physics.SyncTransforms();
            if (Physics.Raycast(ray, out RaycastHit hit, 180f, ~((1 << 8) | (1 << 2)), QueryTriggerInteraction.Ignore))
            {
                end = hit.point;
                PursuerVan enemy = hit.collider.GetComponentInParent<PursuerVan>();
                if (enemy != null)
                {
                    HitMarker = 0.22f;
                    CreateHitEffect(hit.point, hit.normal);
                    enemy.TakeHit();
                }
            }
            DrawBeam(muzzle.position, end);
            PlaySound(shotSound, 0.6f);
            if (Online)
                network.World.BroadcastShot(end, HitMarker > 0f);
            return true;
        }

        public void ReplenishAmmoSupply(ConvoyAmmoPack taken)
        {
            if (supplyPack == taken)
                supplyPack = PrototypeGeometry.CreateAmmoPack(this, ammoSupply);
        }

        public bool TryLoadAmmo(ConvoyAmmoPack pack, ConvoyPlayer actor = null)
        {
            actor = actor != null ? actor : player;
            if (!CanLoadAmmo(pack, actor))
                return false;
            ShotsAvailable = checked(ShotsAvailable + ShotsPerPack);
            pack.Consume();
            RecordLesson(actor, ConvoyTutorial.Lesson.BatteryLoad);
            PlaySound(shotSound, 0.2f);
            return true;
        }

        public bool CanLoadAmmo(ConvoyAmmoPack pack, ConvoyPlayer actor)
        {
            if (!SimulationRunning || pack == null || pack.game != this || pack.Consumed)
                return false;
            Physics.SyncTransforms();
            bool atSocket = CanReachAmmoLoadingPoint(pack, ammoReceiver.position, actor);
            Vector3 breech = gun.TransformPoint(GunLoadingPoint);
            bool atGun = pack.IsCarried && actor.CarriedAmmo == pack &&
                CanReachAmmoLoadingPoint(pack, breech, actor, 1.5f);
            return atSocket || atGun;
        }

        private bool CanReachAmmoLoadingPoint(ConvoyAmmoPack pack, Vector3 target, ConvoyPlayer actor, float reach = 1.2f)
        {
            Vector3 offset = target - pack.transform.position;
            if (offset.magnitude > reach)
                return false;
            foreach (RaycastHit hit in Physics.RaycastAll(pack.transform.position, offset.normalized,
                offset.magnitude, Physics.AllLayers, QueryTriggerInteraction.Ignore))
            {
                if (hit.collider.transform.IsChildOf(pack.transform))
                    continue;
                if (pack.IsCarried && actor.CarriedAmmo == pack &&
                    hit.collider.transform.IsChildOf(actor.transform))
                    continue;
                return false;
            }
            return true;
        }

        private void CreateHitEffect(Vector3 point, Vector3 normal)
        {
            GameObject flash = PrototypeGeometry.Part("Rail impact flash", transform,
                transform.InverseTransformPoint(point), Vector3.one * 0.55f, cyan, false, PrimitiveType.Sphere);
            effects.Add(new Transient { Object = flash, Remaining = 0.12f });
            for (int i = 0; i < 8; i++)
            {
                GameObject spark = PrototypeGeometry.Part("Rail impact spark", transform,
                    transform.InverseTransformPoint(point), Vector3.one * Random.Range(0.04f, 0.12f), cyan, false);
                effects.Add(new Transient { Object = spark, Remaining = Random.Range(0.15f, 0.4f),
                    Velocity = normal * 4f + Random.insideUnitSphere * 3f, Debris = true });
            }
            PlaySound(crashSound, 0.3f);
        }

        public void OnEnemyDestroyed(PursuerVan enemy)
        {
            if (!Pursuers.Remove(enemy))
                return;
            DestroyedVans++;
            Vector3 origin = enemy.transform.position + Vector3.up;
            if (Online)
                network.World.BroadcastExplosion(origin);
            ShowExplosion(origin);
        }

        public void ShowExplosion(Vector3 origin)
        {
            Vector3 localOrigin = transform.InverseTransformPoint(origin);
            PlaySound(explosionSound, 0.7f);
            for (int i = 0; i < 16; i++)
            {
                GameObject shard = PrototypeGeometry.Part("Explosion debris", transform,
                    localOrigin + Random.insideUnitSphere, Vector3.one * Random.Range(0.15f, 0.6f),
                    i % 3 == 0 ? orange : dark, false);
                effects.Add(new Transient { Object = shard, Remaining = Random.Range(0.6f, 1.5f),
                    Velocity = Random.onUnitSphere * Random.Range(3f, 9f) + Vector3.up * 4f, Debris = true });
            }
            GameObject flash = PrototypeGeometry.Part("Explosion flash", transform, localOrigin,
                Vector3.one * 3.5f, orange, false, PrimitiveType.Sphere);
            effects.Add(new Transient { Object = flash, Remaining = 0.18f });
        }

        private void DrawBeam(Vector3 start, Vector3 end)
        {
            GameObject effect = new GameObject("Railgun tracer");
            effect.transform.SetParent(transform);
            LineRenderer line = effect.AddComponent<LineRenderer>();
            line.sharedMaterial = cyan;
            line.positionCount = 2;
            line.SetPosition(0, start);
            line.SetPosition(1, end);
            line.startWidth = 0.075f;
            line.endWidth = 0.025f;
            effects.Add(new Transient { Object = effect, Remaining = 0.12f });
        }

        private void UpdateEffects(float dt)
        {
            for (int i = effects.Count - 1; i >= 0; i--)
            {
                Transient effect = effects[i];
                effect.Remaining -= dt;
                if (effect.Remaining <= 0f)
                {
                    Destroy(effect.Object);
                    effects.RemoveAt(i);
                    continue;
                }
                if (effect.Debris)
                {
                    effect.Velocity += Vector3.down * (12f * dt);
                    effect.Object.transform.position += (effect.Velocity + Vector3.back * CurrentSpeed) * dt;
                    effect.Object.transform.Rotate(new Vector3(55f, 80f, 30f) * dt);
                }
                effects[i] = effect;
            }
        }

        private static AudioClip MakeSound(string clipName, float duration, float frequency, float noise)
        {
            const int sampleRate = 22050;
            float[] samples = new float[Mathf.CeilToInt(sampleRate * duration)];
            System.Random random = new System.Random(42);
            for (int i = 0; i < samples.Length; i++)
            {
                float t = (float)i / sampleRate;
                float envelope = Mathf.Pow(1f - t / duration, 2f);
                samples[i] = (Mathf.Sin(t * frequency * (1f - t) * Mathf.PI * 2f) * (1f - noise)
                    + ((float)random.NextDouble() * 2f - 1f) * noise) * envelope * 0.6f;
            }
            AudioClip clip = AudioClip.Create(clipName, samples.Length, 1, sampleRate, false);
            clip.SetData(samples, 0);
            return clip;
        }

        private void PlaySound(AudioClip clip, float volume)
        {
            if (audioSource != null && clip != null)
                audioSource.PlayOneShot(clip, volume);
        }

